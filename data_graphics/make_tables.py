"""Generate the manuscript's LaTeX tables from the analysis outputs.

Tables are GENERATED, never hand-typed: a number transcribed by hand is a number that
silently goes stale when the analysis is re-run. Every value here is read from the same
CSVs the figures use, so `python make_tables.py` after a re-run keeps the paper honest.

    python make_tables.py            # write all tables to tables/
    python make_tables.py --print    # also echo them to stdout

Output is booktabs + siunitx. Add to the preamble:
    \\usepackage{booktabs}
    \\usepackage{siunitx}
    \\usepackage{multirow}
"""
