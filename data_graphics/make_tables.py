HUMAN_INPUT = os.path.join(REPO, "data_evaluation", "pathologists",
                           "scoring_analysis", "input")
JUDGE_OUTPUT = os.path.join(REPO, "data_evaluation", "vlm_judge", "judge_output")

# score 2 -> near-miss, 1 -> moderate-miss, 0 -> far-miss, -1 -> excluded (no tier).
# Same binning as wrong_answer_tier_agreement.ipynb.
TIER_ORDER = ["near-miss", "moderate-miss", "far-miss"]
_WRONG_COLUMNS = ([f"Evaluation OE_Wrong_Answer_{i}\n(Benchmark 2)" for i in (1, 2)]
                  + [f"Evaluation MCQ_OE_Wrong_Answer_{i}\n(Benchmark 2)"
                     for i in (1, 2, 3, 4)])


def _pooled_human():
    import glob
    frames = []
    directories = sorted(glob.glob(os.path.join(HUMAN_INPUT, "evaluator[0-9]*")),
                         key=lambda p: int(os.path.basename(p).replace("evaluator", "")))
    for directory in directories:
        path = os.path.join(directory, "pathopen_eval_data.csv")
        if os.path.exists(path):
            # Row 0 is a second header line in these exports.
            frames.append(pd.read_csv(path).drop(index=0).reset_index(drop=True))
    return pd.concat(frames, ignore_index=True)


def _confusion(judge_key):
    """3x3 counts, rows = pathologist tier, columns = judge tier."""
    import numpy as np
    human = _pooled_human()
    judge = pd.read_csv(os.path.join(JUDGE_OUTPUT, f"evaluator_{judge_key}",
                                     "pathopen_eval_data.csv"))
    merged = human.merge(judge, on="Image_ID", suffixes=("_human", "_judge"))
    matrix = np.zeros((3, 3), dtype=int)
    index_of = {2: 0, 1: 1, 0: 2}
    for column in _WRONG_COLUMNS:
        h = pd.to_numeric(merged.get(f"{column}_human", merged.get(column)),
                          errors="coerce")
        j = pd.to_numeric(merged.get(f"{column}_judge", merged.get(column)),
                          errors="coerce")
        for human_value, judge_value in zip(h, j):
            if human_value in index_of and judge_value in index_of:
                matrix[index_of[human_value], index_of[judge_value]] += 1
    return matrix


def table_s3_judge_calibration() -> str:
    """Supplementary: WHY the judges fail to reproduce the tiering.

    Reporting kappa alone says the agreement is poor; it does not say how. The marginals
    show the failure has a specific shape - both judges apply a systematically more
    generous plausibility threshold, inflating near-miss - which is diagnosable and
    potentially correctable, and is a more useful finding than a low kappa."""
    import numpy as np
    agreement = pd.read_csv(os.path.join(AGREE, "wrong_answer_tier_agreement.csv"))

    lines = [
        r"% Generated by make_tables.py - do not edit by hand.",
        r"\begin{table}[t]",
        r"\centering\small",
        r"\caption{\textbf{Why VLM judges do not reproduce the pathologists' difficulty "
        r"tiers.} Both judges assign the tiers with a systematically more generous "
        r"threshold rather than at random: each inflates the near-miss category "
        r"$2.4$--$3.0\times$ relative to the pathologists, and InternVL assigns far-miss to "
        r"only $14.2\%$ of items against the pathologists' $50.5\%$. Per-tier recall shows "
        r"the consequence -- InternVL calls an item near-miss $52.7\%$ of the time when the "
        r"pathologist did, but also $51.1\%$ of the time when the pathologist said "
        r"moderate-miss, so its assignment is close to independent of theirs. Agreement is "
        r"markedly worse on OE-native distractors, which are free text, than on MCQ-derived "
        r"ones, which are written as formatted options -- $2.7\times$ for InternVL and "
        r"$1.5\times$ for Qwen -- so the automation gap is widest exactly where the "
        r"distractor is not already option-shaped. This is a calibration failure, not "
        r"noise, and it is what makes Benchmark~2 unsuitable for automation in its "
        r"present form.}",
        r"\label{tab:judge-calibration}",
        r"\begin{tabular}{l l S[table-format=2.1] S[table-format=2.1] S[table-format=2.1]"
        r" S[table-format=1.2]}",
        r"\toprule",
        r" & & \multicolumn{3}{c}{Tier assigned (\%)} & {Near-miss} \\",
        r"\cmidrule(lr){3-5}",
        r"Rater & Split & {Near} & {Moderate} & {Far} & {inflation} \\",
        r"\midrule",
    ]

    matrices = {key: _confusion(key) for key in ("internvl", "qwenvl")}
    reference = matrices["internvl"]
    human_marginal = [100 * reference[i, :].sum() / reference.sum() for i in range(3)]
    lines.append("Pathologists & all & "
                 + " & ".join(f"{v:.1f}" for v in human_marginal) + r" & {--} \\")
    display = {"internvl": "InternVL judge", "qwenvl": "Qwen judge"}
    for key, matrix in matrices.items():
        judge_marginal = [100 * matrix[:, j].sum() / matrix.sum() for j in range(3)]
        inflation = judge_marginal[0] / human_marginal[0]
        lines.append(f"{display[key]} & all & "
                     + " & ".join(f"{v:.1f}" for v in judge_marginal)
                     + f" & {inflation:.2f} \\\\")

    lines += [
        r"\midrule",
        r"\multicolumn{6}{l}{\emph{Per-tier recall: what the judge said, given what the "
        r"pathologist said}} \\",
        r"\midrule",
    ]
    for key, matrix in matrices.items():
        for i, tier in enumerate(TIER_ORDER):
            total = matrix[i, :].sum()
            recall = [100 * matrix[i, j] / total for j in range(3)]
            lines.append(f"{display[key]} & path.\\ said {tier} & "
                         + " & ".join(f"{v:.1f}" for v in recall) + r" & {--} \\")

    # Weighted kappa by distractor source. This is the finding that judges do 2-3x worse
    # on free-text distractors, so it is a visible row block, not a footnote. The three
    # numeric columns are re-labelled for this block via a spanning subheader, because
    # mean/min/max are not tier percentages and must not sit under those headings.
    lines += [
        r"\midrule",
        r"\multicolumn{6}{l}{\emph{Weighted $\kappa$ against the pathologists, by source of "
        r"the distractor}} \\",
        r"\cmidrule(lr){3-5}",
        r" & & {Mean} & {Min} & {Max} & {Cells} \\",
        r"\midrule",
    ]
    for key in ("internvl", "qwenvl"):
        for source, label in (("OE_native", "OE-native (free text)"),
                              ("MCQ_derived", "MCQ-derived (option)")):
            rows = agreement[(agreement.judge == key) & (agreement.source == source)]
            lines.append(f"{display[key]} & {label} & "
                         f"{rows.weighted_kappa.mean():.3f} & "
                         f"{rows.weighted_kappa.min():.3f} & "
                         f"{rows.weighted_kappa.max():.3f} & "
                         f"{{{len(rows)}}} \\\\")

    # The ratio is the point of the block; state it rather than leaving it to be divided.
    ratios = []
    for key in ("internvl", "qwenvl"):
        oe = agreement[(agreement.judge == key)
                       & (agreement.source == "OE_native")].weighted_kappa.mean()
        mcq = agreement[(agreement.judge == key)
                        & (agreement.source == "MCQ_derived")].weighted_kappa.mean()
        ratios.append(f"{display[key]} ${mcq / oe:.1f}\\times$")

    lines += [r"\bottomrule", r"\end{tabular}",
              r"\begin{flushleft}\footnotesize Agreement is markedly worse on OE-native "
              r"distractors, which are free text, than on MCQ-derived ones, which are "
              r"written as formatted options ("
              + "; ".join(ratios) + r" higher $\kappa$ on MCQ-derived). Mean, min and max "
              r"are taken across that judge's criteria and distractor slots."
              r"\end{flushleft}",
              r"\end{table}", ""]
    return "\n".join(lines)


