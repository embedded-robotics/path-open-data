def table1_dataset_quality() -> str:
    r"""Main-text table: the headline Pillar 1 comparison.

    Two separate sn-jnl incompatibilities force the structure below. The class redefines
    `table' to wrap its body in `threeparttable', which (i) breaks a scaling box placed
    inside it -- the box leaves a group open and the float dies with "Missing \endgroup
    inserted" -- and (ii) silently DROPS the whole float, caption and \label included, if
    its body is a box rather than a real `tabular'. So the tabular is built into a savebox
    before the float, and the float uses the class's own unwrapped `tableorg', which has no
    threeparttable and both scales and labels correctly. `tableorg' still numbers as
    "Table N" and \ref resolves normally. Preamble needs \newsavebox{\pathopentablebox}
    and siunitx.
    """
    scores, homogeneity, mann_whitney = _load()
    human = mann_whitney[mann_whitney.rater == "human"].set_index("criterion")

    body = [
        r"\begin{tabular}{l"
        r" S[table-format=1.2] S[table-format=1.2]"
        r" S[table-format=2.1] S[table-format=2.1]"
        r" S[table-format=2.1] S[table-format=2.1]"
        r" S[table-format=1.2] S[table-format=1.2]"
        r" c}",
        r"\toprule",
        r" & \multicolumn{2}{c}{Mean score} & \multicolumn{2}{c}{\% max score}"
        r" & \multicolumn{2}{c}{\% unscorable} & \multicolumn{2}{c}{Rater spread}"
        r" & {Effect size} \\",
        r"\cmidrule(lr){2-3} \cmidrule(lr){4-5} \cmidrule(lr){6-7} \cmidrule(lr){8-9}",
        r"Criterion & {PathOPEN} & {PathVQA} & {PathOPEN} & {PathVQA}"
        r" & {PathOPEN} & {PathVQA} & {PathOPEN} & {PathVQA} & {[95\% CI]} \\",
        r"\midrule",
    ]

    for benchmark, criterion, effect_key, label in PILLAR1_ROWS:
        cells = {}
        for source, key in (("PathOPEN", "po"), ("Filtered_PathVQA", "pv")):
            subset = scores[(scores.dataset == source)
                            & (scores.benchmark == benchmark)
                            & (scores.criterion == criterion)]
            cells[key] = {
                "pct_max": subset.pct_2.mean(),
                "pct_defect": subset["pct_-1"].mean(),
                "spread": subset["mean"].max() - subset["mean"].min(),
            }
        row = human.loc[effect_key]
        effect = (f"{row.rank_biserial:.2f} "
                  f"[{row.rb_ci_low:.2f}, {row.rb_ci_high:.2f}]")
        body.append(
            f"{label} & {row.mean_pathopen:.2f} & {row.mean_pathvqa:.2f} & "
            f"{cells['po']['pct_max']:.1f} & {cells['pv']['pct_max']:.1f} & "
            f"{cells['po']['pct_defect']:.1f} & {cells['pv']['pct_defect']:.1f} & "
            f"{cells['po']['spread']:.2f} & {cells['pv']['spread']:.2f} & "
            f"{effect} \\\\")

    body += [r"\bottomrule", r"\end{tabular}"]

    out = [
        r"% Generated by make_tables.py - do not edit by hand.",
        r"%% Built into a savebox before the float, and placed in the class's unwrapped",
        r"%% `tableorg' float: sn-jnl's `table' wraps its body in threeparttable, which both",
        r"%% breaks a scaling box and silently drops any float whose body is a box (losing",
        r"%% the caption and \label). Needs \newsavebox{\pathopentablebox} + siunitx.",
        r"\sbox{\pathopentablebox}{%",
    ] + body + [
        r"}",
        r"",
        r"\begin{tableorg}[t]",
        r"\centering",
        r"\caption{\textbf{PathOPEN item quality against filtered PathVQA.} "
        r"Scores are on the ordinal scale $\{-1,0,1,2\}$, where $-1$ marks an item a "
        r"pathologist could not evaluate. Mean and effect size pool the five "
        r"pathologists; \% max, \% unscorable and rater spread are computed per "
        r"pathologist and then averaged, so the mean and \% max columns need not move "
        r"together. These per-rater averages run over all five pathologists' pools, "
        r"whereas Fig.~\ref{fig:pillar1}b reports unscorable rates over the 231-item "
        r"subset the VLM judges also rated; the two therefore differ. "
        r"Effect size is the rank-biserial correlation with a bootstrapped "
        r"95\% CI (2{,}000 resamples); negative values indicate PathOPEN ranks higher. "
        r"Rater spread is the range of the five pathologists' mean scores -- smaller is "
        r"more consistent.}",
        r"\label{tab:dataset-quality}",
        r"\sisetup{table-format=-1.3}",
        r"\resizebox{\linewidth}{!}{\usebox{\pathopentablebox}}",
        r"\end{tableorg}",
        r"",
    ]
    return "\n".join(out)



# Cases 9 and 79 are single-image cases whose image was never retrieved from the
# collection store: no original and no augmentations exist for either, and their
# `Images` entry in processed/data.json is present but empty. Every image-dependent
# count therefore has an as-collected value (231 images) and an as-released value
# (229). The release figures are the ones to publish.
MISSING_IMAGE_CASES = {9, 79}
AUGMENTATIONS_PER_IMAGE = 30


def _pathopen_counts(available_only: bool) -> dict:
    """Question-image pair counts, read from the raw collection responses.

    Each question applies to every image of its case, so pair counts exceed question
    counts. With available_only=True the two unretrieved images contribute nothing.
    """
    raw = pd.read_csv(os.path.join(REPO, "pathopen_data", "raw", "data.csv"))
    image_columns = [c for c in raw.columns if c.startswith("Upload Image")]
    images_per_case = raw[image_columns].notna().sum(axis=1)

    counts = dict(oe_correct=0, oe_wrong=0, mcq=0, close_ended=0,
                  cases=len(raw), oe_questions=0, oe_with_wrong=0)
    for index, row in raw.iterrows():
        case_id = index + 1
        n_images = images_per_case.iloc[index]
        if available_only and case_id in MISSING_IMAGE_CASES:
            n_images = 0
        for slot in (1, 2):
            if pd.notna(row[f"Open Ended - Question {slot}"]):
                counts["oe_questions"] += 1
                counts["oe_correct"] += n_images
                if pd.notna(row[f"Open Ended - Wrong Answer {slot}"]):
                    counts["oe_with_wrong"] += 1
                    counts["oe_wrong"] += n_images
        if pd.notna(row["MCQ - Question"]):
            counts["mcq"] += n_images
        if pd.notna(row["Close-Ended Question 1"]):
            counts["close_ended"] += n_images
    counts["images"] = int(images_per_case.sum()) - (
        len(MISSING_IMAGE_CASES) if available_only else 0)
    counts["mcq_distractors"] = counts["mcq"] * 4
    counts["combined_correct"] = counts["oe_correct"] + counts["mcq"]
    counts["combined_wrong"] = counts["oe_wrong"] + counts["mcq_distractors"]
    return counts


