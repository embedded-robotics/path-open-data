def table_s4_dataset_comparison() -> str:
    """Main-text table: intervals and tests for the cross-dataset difficulty claim.

    Pillar 4's headline is a comparison between datasets, but the pillar reported bare
    point estimates until now - no intervals, no tests - while Pillars 1 and 3 both carry
    bootstrapped CIs. This is what lets a reader judge whether the 22.4-vs-25.7 gap that
    the withdrawal of "harder benchmark" rests on is distinguishable from noise."""
    intervals = pd.read_csv(os.path.join(ZEROSHOT_ANALYSIS,
                                         "dataset_comparison_intervals.csv"))
    tests = pd.read_csv(os.path.join(ZEROSHOT_ANALYSIS, "dataset_comparison_tests.csv"))

    lines = [
        r"% Generated by make_tables.py - do not edit by hand.",
        r"%% Wide table: savebox + `tableorg' pattern, see table1_dataset_quality.",
        r"\sbox{\pathopentablebox}{%",
        r"PLACEHOLDER_OPEN",
        r"\begin{tableorg}[t]",
        r"\centering\small",
        r"\caption{\textbf{Cross-dataset performance with bootstrapped confidence intervals "
        r"and pairwise tests.} Means pool the six zero-shot models, treating each "
        r"(model,~item) pair as one observation; intervals are percentile bootstrap "
        r"(2{,}000 resamples over items). For MCQ the comparable quantity is accuracy above "
        r"chance, because option counts range from 2 to 16 across datasets. Pairwise "
        r"comparisons are two-sided Mann--Whitney $U$ with Holm correction within each "
        r"format; the effect size is the rank-biserial correlation. "
        r"\textbf{Every pairwise difference is significant after correction}, so the "
        r"chance-corrected ordering PathMMU $>$ PathOPEN $>$ PatchVQA is not an artifact of "
        r"point estimates: PathOPEN's interval $[19.88, 24.98]$ sits below PathMMU's "
        r"$[24.42, 27.04]$. On open-ended generation PathOPEN scores far above filtered "
        r"PathVQA (rank-biserial $0.740$), whose 7.8-word references leave the metric with "
        r"little to measure. Item clustering is not modelled, which makes these intervals "
        r"mildly anti-conservative.}",
        r"\label{tab:dataset-comparison}",
        r"\resizebox{\linewidth}{!}{\usebox{\pathopentablebox}}",
        r"\end{tableorg}",
        r"PLACEHOLDER_CLOSE",
        r"\begin{tabular}{l l S[table-format=4.0] S[table-format=2.2] c}",
        r"\toprule",
        r"Format & Dataset & {Items} & {Mean} & {95\% CI} \\",
        r"\midrule",
    ]

    for fmt in ("MCQ (accuracy)", "MCQ (above chance)", "Close-ended", "Open-ended"):
        block = intervals[intervals.format == fmt]
        if block.empty:
            continue
        for position, (_, row) in enumerate(block.sort_values("mean", ascending=False)
                                            .iterrows()):
            label = fmt if position == 0 else ""
            lines.append(f"{label} & {DATASET_LABEL.get(row.dataset, row.dataset)} & "
                         f"{int(row.n_items)} & {row['mean']:.2f} & "
                         f"[{row.ci_low:.2f}, {row.ci_high:.2f}] \\\\")
        lines.append(r"\addlinespace")

    lines += [
        r"\midrule",
        r"\multicolumn{5}{l}{\emph{Pairwise comparisons (Mann--Whitney $U$, Holm-corrected "
        r"within format)}} \\",
        r"\midrule",
        r"Format & Comparison & {} & {Rank-biserial} & {$P_{\mathrm{Holm}}$} \\",
        r"\midrule",
    ]
    for _, row in tests.iterrows():
        comparison = (f"{DATASET_LABEL.get(row.a, row.a)} vs "
                      f"{DATASET_LABEL.get(row.b, row.b)}")
        p_text = ("$<$0.001" if row.p_holm < 0.001 else f"{row.p_holm:.3f}")
        lines.append(f"{row.format} & {comparison} & & {row.rank_biserial:.3f} & "
                     f"{p_text} \\\\")

    lines += [r"\bottomrule", r"\end{tabular}", r"}", ""]
    text = "\n".join(lines)
    head, _, rest = text.partition("PLACEHOLDER_OPEN\n")
    float_block, _, body = rest.partition("PLACEHOLDER_CLOSE\n")
    return head + body.rstrip() + "\n\n" + float_block.rstrip() + "\n"


