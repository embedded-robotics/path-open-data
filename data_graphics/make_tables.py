def table_s1_per_evaluator() -> str:
    """Main-text table: the full per-pathologist score distribution."""
    scores, homogeneity, _ = _load()
    subset = scores[scores.dataset.isin(["PathOPEN", "Filtered_PathVQA"])
                    & scores.benchmark.isin([1, 3])]

    lines = [
        r"% Generated by make_tables.py - do not edit by hand.",
        r"%% Ten columns overflow the text block by ~116pt unscaled, so this uses the",
        r"%% savebox + `tableorg' pattern (see table1_dataset_quality for why).",
        r"\sbox{\pathopentablebox}{%",
        r"PLACEHOLDER_OPEN",
        r"\begin{tableorg}[t]",
        r"\centering\small",
        r"\caption{\textbf{Per-pathologist score distributions.} Each item was rated by "
        r"exactly one pathologist, so no per-item agreement statistic (Fleiss' $\kappa$, "
        r"Krippendorff's $\alpha$) is computable; what can be tested is whether the five "
        r"raters' score \emph{distributions} differ across the pools each of them saw. "
        r"$P$ is from a Kruskal--Wallis test across the five raters. PathOPEN's raters "
        r"differ far less than filtered PathVQA's, and on Benchmark 3 they are "
        r"statistically indistinguishable. Note that PathOPEN's narrow spread is partly "
        r"a ceiling effect: when 84--100\% of each rater's scores are the maximum there "
        r"is little room to disagree.}",
        r"\label{tab:per-evaluator}",
        r"\resizebox{\linewidth}{!}{\usebox{\pathopentablebox}}",
        r"\end{tableorg}",
        r"PLACEHOLDER_CLOSE",
        r"\begin{tabular}{l l S[table-format=4.0]"
        r" S[table-format=1.3] S[table-format=1.3] S[table-format=1.3]"
        r" S[table-format=1.3] S[table-format=1.3]"
        r" S[table-format=1.2] c}",
        r"\toprule",
        r"Dataset & Criterion & {$n$} & \multicolumn{5}{c}{Pathologist mean score}"
        r" & {Spread} & {$P$} \\",
        r"\cmidrule(lr){4-8}",
        r" & & & {P1} & {P2} & {P3} & {P4} & {P5} & & \\",
        r"\midrule",
    ]

    display = {"PathOPEN": "PathOPEN", "Filtered_PathVQA": "filtered PathVQA"}
    for source in ("PathOPEN", "Filtered_PathVQA"):
        for benchmark, criterion, _, label in PILLAR1_ROWS:
            rows = subset[(subset.dataset == source)
                          & (subset.benchmark == benchmark)
                          & (subset.criterion == criterion)].sort_values("evaluator")
            if rows.empty:
                continue
            test = homogeneity[(homogeneity.dataset == source)
                               & (homogeneity.benchmark == benchmark)
                               & (homogeneity.criterion == criterion)]
            p_value = test.kruskal_p.iloc[0] if not test.empty else float("nan")
            p_text = (r"\textbf{n.s.}" if p_value >= 0.05
                      else (r"$<$0.001" if p_value < 0.001 else f"{p_value:.3f}"))
            means = " & ".join(f"{v:.3f}" for v in rows["mean"])
            spread = rows["mean"].max() - rows["mean"].min()
            lines.append(f"{display[source]} & {label} & {int(rows.n.sum())} & {means}"
                         f" & {spread:.2f} & {p_text} \\\\")
        if source == "PathOPEN":
            lines.append(r"\midrule")

    lines += [r"\bottomrule", r"\end{tabular}", r"}", ""]
    # Assemble: savebox body first, then the float that scales it.
    text = "\n".join(lines)
    head, _, rest = text.partition("PLACEHOLDER_OPEN\n")
    float_block, _, body = rest.partition("PLACEHOLDER_CLOSE\n")
    return head + body.rstrip() + "\n\n" + float_block.rstrip() + "\n"


