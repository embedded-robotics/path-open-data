def table_s6_benchmark4_rating() -> str:
    """Main-text table: how reliably was the augmented set rated?

    Pillar 5's Gini identity is arithmetic and unassailable, so the pillar's weak flank is
    5a - "augmentation preserves diagnostic content". The headline 88.3% is a mean over
    five pathologists who differ SIGNIFICANTLY on this benchmark, which is recoverable from
    the released ratings. Stating it is better than having a reviewer find it: four of the
    five support the claim cleanly, and the fifth found augmented images hard to assess at
    all rather than rating them poor."""
    scores = pd.read_csv(os.path.join(AGREE, "evaluator_score_distributions.csv"))
    homogeneity = pd.read_csv(os.path.join(AGREE, "evaluator_homogeneity_tests.csv"))
    agreement = pd.read_csv(os.path.join(AGREE, "judge_pathologist_weighted_kappa.csv"))

    b4_scores = scores[scores.benchmark == 4]
    b4_homogeneity = homogeneity[homogeneity.benchmark == 4]
    b4_agreement = agreement[agreement.benchmark == 4]

    lines = [
        r"% Generated by make_tables.py - do not edit by hand.",
        r"\begin{table}[t]",
        r"\centering\small",
        r"\caption{\textbf{Reliability of the Benchmark~4 ratings of augmented images.} "
        r"\emph{Upper block:} each pathologist's mean score and the percentage of images "
        r"they could not evaluate. The five raters differ significantly on both criteria "
        r"(Kruskal--Wallis $P < 0.001$; spread $0.52$ and $0.50$), wider than on PathOPEN's "
        r"original items (Table~S1, spread $0.20$--$0.24$). The divergence is concentrated "
        r"in one rater: evaluator~5 marked $12.2\%$ and $9.5\%$ of augmented images "
        r"unscorable where the other four marked none, so the headline figures ($88.3\%$ "
        r"and $84.2\%$ maximum-score) are means pulled down by a single rater who found "
        r"augmented images hard to \emph{assess} rather than poor in content. "
        r"\emph{Lower block:} judge-versus-pathologist agreement. As in Table~S1 the "
        r"prevalence of maximum scores collapses $\kappa$ while exact agreement stays near "
        r"$80\%$: seven of the eight $\kappa$ confidence intervals include zero, so $\kappa$ "
        r"carries essentially no information at this prevalence. Gwet's AC1, stable "
        r"under high prevalence, gives $0.91$--$0.95$. Item-level agreement is therefore "
        r"moderate even though the score \emph{distributions} match closely.}",
        r"\label{tab:benchmark4-rating}",
        r"\begin{tabular}{l l r l r}",
        r"\toprule",
        r"Criterion & Rater & {Mean} & {\% max} & {\% unscorable} \\",
        r"\midrule",
    ]

    for criterion in ("Clinical Relevance", "Visual Grounding"):
        block = b4_scores[b4_scores.criterion == criterion].sort_values("evaluator")
        for position, (_, row) in enumerate(block.iterrows()):
            label = criterion if position == 0 else ""
            rater = "P" + row.evaluator.replace("evaluator", "")
            lines.append(f"{label} & {rater} & {row['mean']:.2f} & {row.pct_2:.1f} & "
                         f"{row['pct_-1']:.1f} " + r"\\")
        test = b4_homogeneity[b4_homogeneity.criterion == criterion]
        if not test.empty:
            spread = test.mean_spread.iloc[0]
            p_value = test.kruskal_p.iloc[0]
            p_text = r"$<$0.001" if p_value < 0.001 else f"{p_value:.3f}"
            lines.append(r" & \emph{spread / $P$} & " + f"{spread:.2f} & "
                         + r"\multicolumn{2}{c}{" + p_text + r"} \\")
        lines.append(r"\addlinespace")

    lines += [
        r"\midrule",
        r"\multicolumn{5}{l}{\emph{Judge versus pathologist on the same augmented images}} \\",
        r"\midrule",
        r"Criterion & Judge, slot & {Exact \%} & {$\kappa$ [95\% CI]} & {AC1} \\",
        r"\midrule",
    ]
    # Each (criterion, judge) pair has two rows - the two augmented OE slots. Print both:
    # the two kappas differ widely (e.g. 0.237 vs 0.013) but seven of the eight CIs include
    # zero, so a single averaged point estimate would imply precision that is not there.
    for criterion in ("Clinical Relevance", "Visual Grounding"):
        block = b4_agreement[b4_agreement.criterion == criterion].sort_values(
            ["judge", "question_type"])
        for position, (_, row) in enumerate(block.iterrows()):
            label = criterion if position == 0 else ""
            judge = "InternVL" if row.judge == "internvl" else "Qwen"
            slot = row.question_type.rsplit("_", 1)[-1]
            lines.append(
                f"{label} & {judge}, {slot} & {row.exact_agreement_pct:.1f} & "
                f"{row.weighted_kappa:.2f} [{row.kappa_ci_low:.2f}, {row.kappa_ci_high:.2f}] & "
                f"{row.gwet_ac1:.3f} " + r"\\")
        lines.append(r"\addlinespace")

    if lines[-1] == r"\addlinespace":
        lines.pop()
    lines += [r"\bottomrule", r"\end{tabular}",
              r"\begin{flushleft}\footnotesize Slots 1 and 2 are the two augmented "
              r"open-ended question slots. $\kappa$ is quadratic-weighted; $n=173$ and "
              r"$168$."
              r"\end{flushleft}",
              r"\end{table}", ""]
    return "\n".join(lines)


